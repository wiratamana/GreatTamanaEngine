TEST(AssetScaffoldTemplateTest, ScreenPostProcessPassFirstScaffoldWithBothAnchorsAutoWiresAtPriorityZero)
{
    ActiveProjectStateRestorer restorer;
    TempScratchProjectDirectory scratch("ScreenPassFirstAutoWire");
    ActiveProjectAssemblyState::Instance().SetActive("ScratchProject", scratch.Path());

    // Write the target <ProjectName>Game.cpp BY HAND, with both real PHASE2
    // anchor comment blocks present, exactly as a real
    // CreateNewProjectAssembly()-created project's Assets/ScratchProjectGame.cpp
    // would look - this scratch fixture is not itself created through that
    // real entry point.
    const std::filesystem::path gameCppPath = scratch.AssetsPath() / "ScratchProjectGame.cpp";
    {
        std::ofstream stream(gameCppPath, std::ios::binary);
        stream << BuildScratchGameCppWithAnchors("ScratchProject");
    }

    EditorProjectLifecycleCapability capability;
    const IAssetScaffoldingCapability::ScaffoldOutcome outcome =
        capability.CreateAssetScaffold(AssetScaffoldKind::ScreenPostProcessPass, "Foo");

    ASSERT_TRUE(outcome.success) << outcome.errorMessage;
    ASSERT_EQ(outcome.createdFiles.size(), 1u);
    EXPECT_EQ(outcome.createdFiles[0], "FooScreenPass.cpp");
    EXPECT_NE(outcome.reminderMessage.find("automatically wired"), std::string::npos);

    ASSERT_TRUE(std::filesystem::exists(scratch.AssetsPath() / "FooScreenPass.cpp"));
    const std::string screenPassContent = ReadFile(scratch.AssetsPath() / "FooScreenPass.cpp");
    EXPECT_EQ(screenPassContent.find("__NAME__"), std::string::npos);
    EXPECT_NE(screenPassContent.find("RegisterFooScreenPass"), std::string::npos);
    EXPECT_NE(screenPassContent.find("\"Foo.ScreenTint\""), std::string::npos);
    // better-render-pass-1 campaign, PHASE9 (Decision D3) - the generated
    // template now calls core.AddScreenPostProcessPass(), whose signature
    // puts `priority` as its LAST positional argument (after the callback/
    // blendMode) - the generated line therefore ends in a closing paren +
    // semicolon ("/*priority=*/0);"), never a trailing comma like the old
    // core.RegisterProjectRenderFeature()-based template did.
    EXPECT_NE(screenPassContent.find("/*priority=*/0);"), std::string::npos);
    EXPECT_NE(screenPassContent.find("core.AddScreenPostProcessPass("), std::string::npos);

    // The scratch project's own Game.cpp now contains the correct forward
    // declaration + call line, auto-wired in.
    const std::string gameCppContent = ReadFile(gameCppPath);
    EXPECT_NE(gameCppContent.find("void RegisterFooScreenPass(gte::Core& core);"), std::string::npos);
    EXPECT_NE(gameCppContent.find("    RegisterFooScreenPass(core);"), std::string::npos);
}

