std::string BuildScratchGameCppWithAnchors(const std::string& name)
{
    return
        "// " + name + "Game.cpp - generated by the Editor's \"Create New Project\" action.\n"
        "// This is your project's Game half's entry point. Add your own render\n"
        "// passes/ECS components/systems here, or use the \"Project\" panel's\n"
        "// right-click \"Create\" menu (once this project is open/active) to scaffold\n"
        "// a starting Render Pass / Compute Shader / Vertex+Fragment Shader pair.\n"
        "#include \"../Libraries/ProjectAssemblyExports.h\"\n"
        "#include \"../../../src/Core/Core.h\"\n"
        "\n"
        "// GTE_AUTO_REGISTER_FORWARD_DECLARATIONS - do not remove or edit this\n"
        "// line. The Editor's \"Create\" scaffolding tools (Render Pass / Compute\n"
        "// Shader / Screen Post-Process Pass) insert a forward declaration for\n"
        "// each newly-scaffolded Register<Name>...(core) function directly BELOW\n"
        "// this line, automatically. Removing this comment does not break\n"
        "// anything - a future scaffold action simply cannot auto-wire itself in\n"
        "// anymore, and falls back to reminding you to wire it in by hand instead.\n"
        "\n"
        "namespace {\n"
        "\n"
        "void RegisterProject(gte::Core& core)\n"
        "{\n"
        "    // GTE_AUTO_REGISTER_ANCHOR - do not remove or edit this line. The\n"
        "    // Editor's \"Create\" scaffolding tools insert their own\n"
        "    // Register<Name>...(core); call directly ABOVE this comment,\n"
        "    // automatically, when they can find it. Removing this comment does\n"
        "    // not break anything - a future scaffold action simply cannot\n"
        "    // auto-wire itself in anymore, and falls back to reminding you to\n"
        "    // wire it in by hand instead.\n"
        "}\n"
        "\n"
        "} // namespace\n"
        "\n"
        "GTE_DEFINE_PROJECT_EXPORTS_GAME(RegisterProject)\n";
}

// RAII helper restoring ActiveProjectAssemblyState to whatever it was before
// this test touched it - every test uses this so no scratch project name
// or "no active project" state ever leaks into whichever test happens to
// run next in this same binary.
class ActiveProjectStateRestorer {
public:
    ActiveProjectStateRestorer() : m_before(ActiveProjectAssemblyState::Instance().GetActive()) {}
    ~ActiveProjectStateRestorer()
    {
        if (m_before.hasActiveProject) {
            ActiveProjectAssemblyState::Instance().SetActive(m_before.name, m_before.sourceDirectory);
        } else {
            ActiveProjectAssemblyState::Instance().Clear();
        }
    }

private:
    ActiveProjectAssemblyInfo m_before;
};

