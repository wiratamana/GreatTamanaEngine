TEST(ScreenPassAutoWireTest, BothAnchorsPresentInsertsBothLinesCorrectlyPositioned)
{
    TempScratchFile scratch("BothAnchorsPresent");
    const std::string original = BothAnchorsPresentContent();
    WriteRawFile(scratch.Path(), original);

    const bool result = TryAutoWireRegisterCall(scratch.Path(), "RegisterFooScreenPass");

    EXPECT_TRUE(result);
    const std::string content = ReadRawFile(scratch.Path());

    // Both new lines present, exactly once each.
    EXPECT_EQ(CountOccurrences(content, "void RegisterFooScreenPass(gte::Core& core);"), 1);
    EXPECT_EQ(CountOccurrences(content, "    RegisterFooScreenPass(core);"), 1);

    // Placement (Option B, user-confirmed): immediately AFTER the whole
    // anchor comment block ends - never splitting it.
    EXPECT_NE(content.find(
        "// anymore, and falls back to reminding you to wire it in by hand instead.\n"
        "void RegisterFooScreenPass(gte::Core& core);\n"
        "\n"
        "namespace {"),
        std::string::npos);
    EXPECT_NE(content.find(
        "    // wire it in by hand instead.\n"
        "    RegisterFooScreenPass(core);\n"
        "}\n"),
        std::string::npos);

    // Every original line survives - exactly two new lines were added, no
    // existing line was edited/removed.
    EXPECT_NE(content.find("GTE_AUTO_REGISTER_FORWARD_DECLARATIONS"), std::string::npos);
    EXPECT_NE(content.find("GTE_AUTO_REGISTER_ANCHOR"), std::string::npos);
    EXPECT_NE(content.find("GTE_DEFINE_PROJECT_EXPORTS_GAME(RegisterProject)"), std::string::npos);
    EXPECT_EQ(std::count(content.begin(), content.end(), '\n'),
        std::count(original.begin(), original.end(), '\n') + 2);
}

