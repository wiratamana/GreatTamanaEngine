TEST(ScreenPassAutoWireTest, IdempotentSecondCallForSameNameWritesNothingNew)
{
    TempScratchFile scratch("Idempotent");
    WriteRawFile(scratch.Path(), BothAnchorsPresentContent());

    const bool firstResult = TryAutoWireRegisterCall(scratch.Path(), "RegisterFooScreenPass");
    ASSERT_TRUE(firstResult);
    const std::string afterFirstCall = ReadRawFile(scratch.Path());

    const bool secondResult = TryAutoWireRegisterCall(scratch.Path(), "RegisterFooScreenPass");

    EXPECT_TRUE(secondResult);
    EXPECT_EQ(ReadRawFile(scratch.Path()), afterFirstCall);
}

TEST(ScreenPassAutoWireTest, CommentedOutCallTreatedAsNotWiredInsertsFreshActiveCall)
{
    TempScratchFile scratch("CommentedOutCall");
    WriteRawFile(scratch.Path(), BothAnchorsPresentWithCommentedOutCallContent());

    const bool result = TryAutoWireRegisterCall(scratch.Path(), "RegisterFooScreenPass");

    EXPECT_TRUE(result);
    const std::string content = ReadRawFile(scratch.Path());

    // The OLD, manually-commented-out call line survives, untouched.
    EXPECT_NE(content.find("    // RegisterFooScreenPass(core);\n"), std::string::npos);
    // A NEW, active (uncommented) call line was inserted too - never
    // mistaking the commented-out line for "already wired".
    EXPECT_NE(content.find("\n    RegisterFooScreenPass(core);\n}\n"), std::string::npos);
    // Exactly one commented occurrence and one active occurrence - two total.
    EXPECT_EQ(CountOccurrences(content, "RegisterFooScreenPass(core);"), 2);
}

TEST(ScreenPassAutoWireTest, TwoDifferentNamesCalledInSequenceBothPresentAndCorrectlyPositioned)
{
    TempScratchFile scratch("TwoDifferentNames");
    WriteRawFile(scratch.Path(), BothAnchorsPresentContent());

    const bool firstResult = TryAutoWireRegisterCall(scratch.Path(), "RegisterAlphaScreenPass");
    ASSERT_TRUE(firstResult);
    const bool secondResult = TryAutoWireRegisterCall(scratch.Path(), "RegisterBetaScreenPass");
    ASSERT_TRUE(secondResult);

    const std::string content = ReadRawFile(scratch.Path());

    // Both forward declarations present, each exactly once - the second
    // insertion's own point resolution was not thrown off by the first
    // insertion's already-shifted line indices (this file re-reads fresh
    // from disk on every call, so this is also a real regression proof for
    // that exact hazard).
    EXPECT_EQ(CountOccurrences(content, "void RegisterAlphaScreenPass(gte::Core& core);"), 1);
    EXPECT_EQ(CountOccurrences(content, "void RegisterBetaScreenPass(gte::Core& core);"), 1);
    // Both active call lines present, each exactly once.
    EXPECT_EQ(CountOccurrences(content, "    RegisterAlphaScreenPass(core);"), 1);
    EXPECT_EQ(CountOccurrences(content, "    RegisterBetaScreenPass(core);"), 1);
    // Neither anchor's own comment block was corrupted.
    EXPECT_NE(content.find("GTE_AUTO_REGISTER_FORWARD_DECLARATIONS"), std::string::npos);
    EXPECT_NE(content.find("GTE_AUTO_REGISTER_ANCHOR"), std::string::npos);
}

