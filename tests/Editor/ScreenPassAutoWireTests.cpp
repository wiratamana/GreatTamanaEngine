class TempScratchFile {
public:
    explicit TempScratchFile(const std::string& uniqueSuffix)
        : m_path(std::filesystem::temp_directory_path() /
              ("gte_screen_pass_auto_wire_tests_" + uniqueSuffix + ".cpp"))
    {
        std::filesystem::remove(m_path);
    }

    ~TempScratchFile()
    {
        std::error_code ignored;
        std::filesystem::remove(m_path, ignored);
    }

    const std::filesystem::path& Path() const { return m_path; }

private:
    std::filesystem::path m_path;
};

void WriteRawFile(const std::filesystem::path& path, const std::string& content)
{
    std::ofstream stream(path, std::ios::binary);
    stream << content;
}

std::string ReadRawFile(const std::filesystem::path& path)
{
    std::ifstream stream(path, std::ios::binary);
    return std::string((std::istreambuf_iterator<char>(stream)), std::istreambuf_iterator<char>());
}

int CountOccurrences(const std::string& haystack, const std::string& needle)
{
    int count = 0;
    std::size_t pos = 0;
    while ((pos = haystack.find(needle, pos)) != std::string::npos) {
        ++count;
        pos += needle.size();
    }
    return count;
}

